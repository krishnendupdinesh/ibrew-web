export function readServerCatalog(): StoreProduct[] {
  try {
    if (!fs.existsSync(DATA_FILE)) {
      fs.mkdirSync(DATA_DIR, { recursive: true });
      fs.writeFileSync(DATA_FILE, JSON.stringify(INITIAL_SERVER_PRODUCTS, null, 2), "utf8");
      return [...INITIAL_SERVER_PRODUCTS];
    }
    const raw = fs.readFileSync(DATA_FILE, "utf8");
    const parsed = JSON.parse(raw);
    if (Array.isArray(parsed) && parsed.length > 0) {
      return parsed;
    }
  } catch {
    // fallback to in-memory initial list
  }
  return [...INITIAL_SERVER_PRODUCTS];
}

export function writeServerCatalog(products: StoreProduct[]) {
  try {
    fs.mkdirSync(DATA_DIR, { recursive: true });
    fs.writeFileSync(DATA_FILE, JSON.stringify(products, null, 2), "utf8");
  } catch {
    // ignore write error
  }
}

export function filterCatalogBySection(
  products: StoreProduct[],
  section?: string | null
): StoreProduct[] {
  if (!section) return products;
  return products.filter((p) => p.section === (section as ProductSection));
}

